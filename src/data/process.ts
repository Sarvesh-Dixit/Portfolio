/** A general approach, not a claim that every project followed it identically. */
export const processStages = [
  { title: 'Understand', body: 'Identify the problem, the intended users, the requirements and the constraints.' },
  { title: 'Design', body: 'Plan the architecture, database relationships, user roles, APIs and data flow.' },
  { title: 'Develop', body: 'Build the frontend, backend, database functionality and core features.' },
  { title: 'Integrate', body: 'Connect external services, APIs, messaging platforms and other system components.' },
  { title: 'Test & improve', body: 'Find issues, refine functionality, improve usability and prepare for deployment.' },
];
